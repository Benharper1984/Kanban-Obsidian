// Helper to get filter icon by name
export function getFilterIcon(iconName: string): string {
	switch (iconName) {
		case 'layers':
			return Icons.layers;
		case 'file-text':
			return Icons.fileText;
		case 'image':
			return Icons.image;
		case 'paperclip':
			return Icons.paperclip;
		case 'folder':
			return Icons.folder;
		default:
			return Icons.layers;
	}
}

// Helper to get card icon by type
export function getCardIcon(type: string): string {
	switch (type) {
		case 'folder':
			return Icons.folder;
		case 'markdown':
			return Icons.markdown;
		case 'image':
			return Icons.image;
		default:
			return Icons.attachment;
	}
}
